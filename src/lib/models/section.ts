
import type { SectionMetadata } from '@/types/section-metadata';
import {
  addVersionToHistory,
  createEditedMetadata,
  createFailedMetadata,
  createGeneratedMetadata,
  createGeneratingMetadata,
  defaultSectionMetadata,
  SectionStatus,
  updateContentStatistics,
} from '@/types/section-metadata';
import { v4 as uuidv4 } from 'uuid';
import { z } from 'zod';
import {
  Behavior,
  BehaviorSchema,
  defaultControls,
  GenerationControlState,
  GenerationControlStateSchema,
  SectionContext,
  SectionContextSchema,
  SectionType,
  SectionTypeSchema,
} from './control-types';
import type { Project } from './project';

export const SectionPropertiesSchema = z.object({
  id: z.string().optional(),
  title: z.string(),
  type: SectionTypeSchema,
  content: z.string().optional(),
  prompt: z.string().optional(),
  rules: z.array(z.string()).optional(),
  guidelines: z.array(z.string()).optional(),
  constraints: z.array(z.string()).optional(),
  behaviors: z.array(BehaviorSchema).optional(),
  controls: GenerationControlStateSchema.partial().optional(),
  context: SectionContextSchema.partial().optional(),
  metadata: z.record(z.any()).optional(),
});


/**
 * Section Properties Interface
 *
 * Defines the structure for creating or updating a Section instance.
 */
export interface SectionProperties {
  /** Unique identifier (UUID v4). Auto-generated if not provided. */
  id?: string;

  /** Section title/heading */
  title: string;

  /** Section type (report, diagram, code, etc.) */
  type: SectionType;

  /** Section content in Markdown format */
  content?: string;

  /** Generation prompt/instructions */
  prompt?: string;

  /** Writing rules to enforce */
  rules?: string[];

  /** Writing guidelines to follow */
  guidelines?: string[];

  /** Writing constraints/restrictions */
  constraints?: string[];

  /** AI behaviors and personas */
  behaviors?: Behavior[];

  /** Generation control settings (formality, complexity, etc.) */
  controls?: Partial<GenerationControlState>;

  /** Context references (other sections, external files) */
  context?: Partial<SectionContext>;

  /** Section metadata (status, statistics, history) */
  metadata?: Record<string, any>;
}

/**
 * Section Model
 *
 * Immutable class representing a section within a chapter or project.
 * Sections are the atomic content units that can be AI-generated or manually edited.
 *
 * @example
 * ```typescript
 * // Create new section
 * const section = new Section({
 *   title: 'Introduction',
 *   type: 'report',
 *   prompt: 'Write an introduction about AI',
 * });
 *
 * // Mark as generating
 * const generating = section.markAsGenerating();
 *
 * // Update with generated content
 * const generated = section.markAsGenerated('gemma-2b', 'Generated content...');
 * ```
 */
export class Section {
  public readonly id: string;
  public readonly title: string;
  public readonly type: SectionType;
  public readonly content: string;
  public readonly prompt: string;
  public readonly rules: readonly string[];
  public readonly guidelines: readonly string[];
  public readonly constraints: readonly string[];
  public readonly behaviors: readonly Behavior[];
  public readonly controls: GenerationControlState;
  public readonly context: SectionContext;
  public readonly metadata: Readonly<Record<string, any>>;

  /**
   * Creates a new Section instance
   *
   * @param props - Section properties
   */
  constructor(props: SectionProperties) {
    this.id = props.id || uuidv4();
    this.title = props.title;
    this.type = props.type;
    this.content = props.content ?? '';
    this.prompt = props.prompt ?? '';
    this.rules = props.rules ?? [];
    this.guidelines = props.guidelines ?? [];
    this.constraints = props.constraints ?? [];
    this.behaviors = props.behaviors ?? [];

    // Initialize metadata with defaults if not provided
    this.metadata = props.metadata ? {
      ...defaultSectionMetadata,
      ...props.metadata,
    } : { ...defaultSectionMetadata };

    this.controls = {
      ...defaultControls,
      ...props.controls,
      outputStyle: {
        ...defaultControls.outputStyle,
        ...(props.controls?.outputStyle || {}),
      },
    };

    this.context = {
      sections: props.context?.sections ?? {},
      externalContext: props.context?.externalContext ?? {},
    };
  }

  /**
   * Creates a new Section instance with updated properties (immutable update)
   *
   * @param props - Partial properties to update
   * @returns New Section instance with merged properties
   *
   * @example
   * ```typescript
   * const updated = section.with({
   *   title: 'Updated Title',
   *   content: 'New content'
   * });
   * ```
   */
  public with(props: Partial<SectionProperties>): Section {
    return new Section({ ...this.toStateObject(), ...props });
  }

  /**
   * Marks section as currently being generated by AI
   *
   * Updates status to GENERATING and increments attempt counter.
   *
   * @returns New Section instance with updated metadata
   *
   * @example
   * ```typescript
   * const generating = section.markAsGenerating();
   * console.log(generating.getStatus()); // 'generating'
   * ```
   */
  public markAsGenerating(): Section {
    const updatedMetadata = createGeneratingMetadata(this.metadata as SectionMetadata);
    return this.with({ metadata: updatedMetadata });
  }

  /**
   * Marks section as successfully generated by AI
   *
   * Updates status to GENERATED, stores AI model info, updates content statistics,
   * and saves previous version to history.
   *
   * @param aiModel - Name of AI model used (e.g., 'gemma-2b', 'llama3-8b')
   * @param content - Generated content
   * @returns New Section instance with updated content and metadata
   *
   * @example
   * ```typescript
   * const generated = section.markAsGenerated('gemma-2b', 'AI generated content...');
   * console.log(generated.getAiModel()); // 'gemma-2b'
   * console.log(generated.getWordCount()); // calculated from content
   * ```
   */
  public markAsGenerated(aiModel: string, content: string): Section {
    let updatedMetadata = createGeneratedMetadata(this.metadata as SectionMetadata, aiModel);
    updatedMetadata = updateContentStatistics(updatedMetadata, content);

    // Save version history if content changed
    if (this.content && this.content !== content) {
      updatedMetadata = addVersionToHistory(updatedMetadata, this.content);
    }

    return this.with({
      content,
      metadata: updatedMetadata
    });
  }

  /**
   * Marks section as failed generation
   *
   * Updates status to FAILED after unsuccessful AI generation attempt.
   *
   * @returns New Section instance with updated metadata
   *
   * @example
   * ```typescript
   * const failed = section.markAsFailed();
   * console.log(failed.getStatus()); // 'failed'
   * ```
   */
  public markAsFailed(): Section {
    const updatedMetadata = createFailedMetadata(this.metadata as SectionMetadata);
    return this.with({ metadata: updatedMetadata });
  }

  /**
   * Marks section as manually edited by user
   *
   * Updates status to EDITED, updates content statistics, and saves version history.
   *
   * @param content - New content after user edit
   * @returns New Section instance with updated content and metadata
   *
   * @example
   * ```typescript
   * const edited = section.markAsEdited('User edited content...');
   * console.log(edited.getStatus()); // 'edited'
   * ```
   */
  public markAsEdited(content: string): Section {
    let updatedMetadata = createEditedMetadata(this.metadata as SectionMetadata);
    updatedMetadata = updateContentStatistics(updatedMetadata, content);

    // Save version history
    if (this.content && this.content !== content) {
      updatedMetadata = addVersionToHistory(updatedMetadata, this.content);
    }

    return this.with({
      content,
      metadata: updatedMetadata
    });
  }

  /**
   * Updates section content and refreshes statistics
   *
   * If editedByUser is true, marks section as EDITED. Otherwise, updates
   * content without changing status.
   *
   * @param content - New content
   * @param editedByUser - Whether content was edited by user (default: false)
   * @returns New Section instance with updated content
   *
   * @example
   * ```typescript
   * // Programmatic update
   * const updated = section.updateContent('New content');
   *
   * // User edit
   * const userEdited = section.updateContent('User content', true);
   * ```
   */
  public updateContent(content: string, editedByUser: boolean = false): Section {
    if (editedByUser) {
      return this.markAsEdited(content);
    }

    // Just update content and statistics without changing status
    let updatedMetadata = { ...(this.metadata as SectionMetadata) };
    updatedMetadata = updateContentStatistics(updatedMetadata, content);
    updatedMetadata.lastModifiedAt = new Date().toISOString();

    return this.with({
      content,
      metadata: updatedMetadata
    });
  }

  /**
   * Gets current generation status
   *
   * @returns Section status (draft, generating, generated, edited, failed)
   */
  public getStatus(): SectionStatus {
    return (this.metadata as SectionMetadata)?.status || SectionStatus.DRAFT;
  }

  /**
   * Checks if section has been generated or edited
   *
   * @returns True if status is GENERATED or EDITED
   */
  public isGenerated(): boolean {
    const status = this.getStatus();
    return status === SectionStatus.GENERATED || status === SectionStatus.EDITED;
  }

  /**
   * Checks if section is currently being generated
   *
   * @returns True if status is GENERATING
   */
  public isGenerating(): boolean {
    return this.getStatus() === SectionStatus.GENERATING;
  }

  /**
   * Gets AI model name used for generation
   *
   * @returns AI model name (e.g., 'gemma-2b') or undefined
   */
  public getAiModel(): string | undefined {
    return (this.metadata as SectionMetadata)?.aiModel;
  }

  /**
   * Gets word count from content statistics
   *
   * @returns Number of words in content
   */
  public getWordCount(): number {
    return (this.metadata as SectionMetadata)?.wordCount || 0;
  }

  /**
   * Gets estimated reading time in minutes
   *
   * Calculated based on average reading speed (200 words/minute).
   *
   * @returns Estimated read time in minutes
   */
  public getReadTime(): number {
    return (this.metadata as SectionMetadata)?.estimatedReadTime || 0;
  }

  /**
   * Gets generation timestamp
   *
   * @returns ISO datetime string when section was generated, or undefined
   */
  public getGeneratedAt(): string | undefined {
    return (this.metadata as SectionMetadata)?.generatedAt;
  }

  /**
   * Gets number of generation attempts
   *
   * @returns Total attempts made to generate this section
   */
  public getGenerationAttempts(): number {
    return (this.metadata as SectionMetadata)?.generationAttempts || 0;
  }

  /**
   * Builds system prompt for AI generation
   *
   * Constructs comprehensive system prompt including persona, tone, rules,
   * guidelines, constraints, and output format specifications.
   *
   * @returns System prompt string
   *
   * @example
   * ```typescript
   * const systemPrompt = section.buildSystemPrompt();
   * // Use in AI generation request
   * ```
   */
  public buildSystemPrompt(): string {
    const personas = this.behaviors.filter(b => b.type === 'persona').map(b => b.name);
    const behaviorInstructions = this.behaviors.filter(b => b.type === 'behavior').map(b => b.name);

    let systemPrompt = 'You are an advanced AI assistant tailored for academic and technical writing.';

    if (personas.length > 0) {
      systemPrompt += `\n\n**ROLE / PERSONA:**\nAdopt the persona of: ${personas.join(', ')}. Write with the authority, vocabulary, and perspective of this role.`;
    }

    if (this.controls.tone) {
      systemPrompt += `\nMaintain a **${this.controls.tone}** tone throughout.`;
    }

    const allRules = [
      ...this.rules,
      ...behaviorInstructions,
      this.controls.language !== 'default' ? `Output must be in ${this.controls.language}.` : null,
    ].filter(Boolean) as string[];

    if (allRules.length > 0) {
      systemPrompt += `\n\n**MANDATORY RULES:**\n${allRules.map(r => `- ${r}`).join('\n')}`;
    }

    if (this.guidelines.length > 0) {
        systemPrompt += `\n\n**GUIDELINES (Follow these recommendations):**\n${this.guidelines.map(g => `- ${g}`).join('\n')}`;
    }

    if (this.constraints.length > 0) {
      systemPrompt += `\n\n**CONSTRAINTS (DO NOT DO):**\n${this.constraints.map(c => `- ${c}`).join('\n')}`;
    }

    // Output Format Specifics
    if (this.type === 'diagram') {
      systemPrompt += `\n\nOutput ONLY valid PlantUML code inside \`\`\`plantuml blocks. Do not add conversational text.`;
    } else if (this.type === 'code') {
      systemPrompt += `\n\nFocus on producing high-quality, documented code snippets.`;
    }

    return systemPrompt;
  }

  /**
   * Builds action/user prompt for AI generation
   *
   * Constructs detailed instructions including formality, complexity, tone,
   * word count, output styles, and generation controls.
   *
   * @returns Action prompt string combining section prompt with controls
   *
   * @example
   * ```typescript
   * const actionPrompt = section.buildActionPrompt();
   * // Contains: user prompt + formality + complexity + styles
   * ```
   */
  public buildActionPrompt(): string {
    const formalityMap: { [key: number]: string } = { 0: 'very informal and casual', 33: 'balanced and neutral', 67: 'formal and professional', 100: 'very formal and academic' };
    const complexityMap: { [key: number]: string } = { 0: 'very simple and easy to understand', 33: 'clear and straightforward', 67: 'detailed and technical', 100: 'highly complex and expert-level' };

    let instructions: string[] = [];
    const formality = this.controls.formality > 67 ? formalityMap[100] : this.controls.formality > 33 ? formalityMap[67] : this.controls.formality > 0 ? formalityMap[33] : formalityMap[0];
    instructions.push(`The formality should be ${formality}.`);

    const complexity = this.controls.complexity > 67 ? complexityMap[100] : this.controls.complexity > 33 ? complexityMap[67] : this.controls.complexity > 0 ? complexityMap[33] : complexityMap[0];
    instructions.push(`The complexity should be ${complexity}.`);

    if (this.controls.tone) instructions.push(`The tone should be ${this.controls.tone}.`);
    if (this.controls.wordCount) instructions.push(`Aim for a word count of approximately ${this.controls.wordCount} words.`);

    if (this.controls.outputStyle.diagram && this.controls.diagramType) {
        instructions.push(`The output must include a PlantUML diagram of type '${this.controls.diagramType}'.`);
    }
    if (this.controls.outputStyle.code && this.controls.programmingLanguage) {
        instructions.push(`The code blocks should be in ${this.controls.programmingLanguage}.`);
    }
    if (this.controls.outputStyle.table && this.controls.tableCaption) {
        instructions.push(`If a table is generated, it must have the caption: "${this.controls.tableCaption}".`);
    }
    if (this.controls.outputStyle.heading && this.controls.includedHeadings && this.controls.includedHeadings.length > 0) {
        instructions.push(`The heading should cover the following topics: ${this.controls.includedHeadings.join(', ')}.`);
    }

    if (this.controls.language && this.controls.language !== 'default') {
        instructions.push(`The output language must be ${this.controls.language}.`);
    }

    if (this.controls.outputStyle.includeCitations && this.controls.citationStyle) {
        instructions.push(`Use ${this.controls.citationStyle} citation style.`);
    }

    const enabledStyles = Object.entries(this.controls.outputStyle).filter(([key, value]) => value && key !== 'includeCitations').map(([key]) => key);
    if (enabledStyles.length > 0) instructions.push(`The output should primarily include the following elements: ${enabledStyles.join(', ')}.`);

    const additionalInstructions = `\n\n**Additional Instructions:**\n${instructions.join(' ')}`;

    return `${this.prompt}${additionalInstructions}`;
  }

  /**
   * Gets referenced section context as key-value record
   *
   * Retrieves content from other sections referenced in this section's context.
   * Used for providing context to AI during generation.
   *
   * @param project - Project containing all sections
   * @returns Record mapping section titles to their content
   *
   * @example
   * ```typescript
   * const context = section.getContextAsRecord(project);
   * // { "Introduction": "intro content...", "Background": "bg content..." }
   * ```
   */
  public getContextAsRecord(project: Project): Record<string, string> {
      if (!this.context?.sections) return {};
      const contextRecord: Record<string, string> = {};
      for (const sectionId of Object.keys(this.context.sections)) {
          const section = project.getSection(sectionId);
          if (section?.content) {
              contextRecord[section.title] = section.content;
          }
      }
      return contextRecord;
  }

  /**
   * Gets referenced external context files as array
   *
   * Retrieves external files (PDFs, documents) referenced in this section's context.
   * Used for providing external data to AI during generation.
   *
   * @param project - Project containing external files
   * @returns Array of external context objects with fileName, content, and type
   *
   * @example
   * ```typescript
   * const files = section.getExternalContextAsArray(project);
   * // [{ fileName: "research.pdf", content: "...", type: "context" }]
   * ```
   */
  public getExternalContextAsArray(project: Project): { fileName: string; content: string; type: string }[] {
      if (!this.context?.externalContext) return [];
      const externalContextArray = [];
      for (const fileId of Object.keys(this.context.externalContext)) {
          const file = project.externalContext?.find(f => f.id === fileId);
          if (file) {
              externalContextArray.push({
                  fileName: file.fileName,
                  content: file.content,
                  type: this.context.externalContext[fileId]!,
              });
          }
      }
      return externalContextArray;
  }

  /**
   * Converts Section instance to plain object (for persistence/serialization)
   *
   * @returns Plain JavaScript object with all section data
   *
   * @example
   * ```typescript
   * const plainObject = section.toStateObject();
   * localStorage.setItem('section', JSON.stringify(plainObject));
   *
   * // Reconstruct later
   * const restored = new Section(JSON.parse(localStorage.getItem('section')));
   * ```
   */
  public toStateObject(): SectionProperties {
    return {
      id: this.id,
      title: this.title,
      type: this.type,
      content: this.content,
      prompt: this.prompt,
      rules: [...this.rules],
      guidelines: [...this.guidelines],
      constraints: [...this.constraints],
      behaviors: [...this.behaviors],
      controls: this.controls,
      context: this.context,
      metadata: this.metadata,
    };
  }

  /**
   * JSON serialization method (used by JSON.stringify)
   *
   * @returns Plain JavaScript object
   */
  public toJSON(): SectionProperties {
    return this.toStateObject();
  }
}
