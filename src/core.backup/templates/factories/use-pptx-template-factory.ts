/**
 * Template Factory لملفات PPTX
 */

import { useCallback } from 'react';
import { useTemplateManager } from '../managers/use-template-manager';
import type { Template, TemplateCategory, TemplateStyle } from '../types/template-types';

export interface PptxTemplateConfig {
    category: TemplateCategory;
    autoSave?: boolean;
    validateStyles?: boolean;
}

export interface PptxTemplateResult {
    templates: Record<string, Template>;
    activeTemplate: Template | null;
    isLoading: boolean;
    isSaving: boolean;

    // إدارة القوالب
    setActiveTemplate: (templateId: string) => void;
    createPptxTemplate: (name: string, description: string, styles: Record<string, TemplateStyle>) => Promise<string>;
    updatePptxTemplate: (templateId: string, updates: Partial<Template>) => Promise<void>;
    deletePptxTemplate: (templateId: string) => Promise<void>;

    // إدارة الأنماط
    updatePptxStyle: (templateId: string, styleId: string, properties: Record<string, any>) => void;
    addPptxStyle: (templateId: string, style: TemplateStyle) => void;
    removePptxStyle: (templateId: string, styleId: string) => void;

    // الأنماط الافتراضية
    getDefaultPptxStyles: () => Record<string, TemplateStyle>;
    applyPptxStyle: (templateId: string, slideType: string, styleId: string) => void;

    // الوظائف المساعدة
    getPptxTemplatesByCategory: (category: TemplateCategory) => Template[];
    validatePptxTemplate: (template: Template) => boolean;
}

export function createPptxTemplateHook(config: PptxTemplateConfig) {
    return function usePptxTemplate(): PptxTemplateResult {
        const templateManager = useTemplateManager({
            autoSave: config.autoSave ?? true,
            validateStyles: config.validateStyles ?? true,
            onStyleChange: (templateId, styleId, changes) => {
                console.log(`PPTX style changed: ${templateId}.${styleId}`, changes);
            },
            onTemplateChange: (templateId, changes) => {
                console.log(`PPTX template changed: ${templateId}`, changes);
            }
        });

        // إنشاء قالب PPTX جديد
        const createPptxTemplate = useCallback(async (
            name: string,
            description: string,
            styles: Record<string, TemplateStyle>
        ): Promise<string> => {
            const template: Omit<Template, 'id' | 'createdAt' | 'updatedAt'> = {
                name,
                description,
                version: '1.0.0',
                author: 'Generated by Arkan',
                tags: ['pptx', config.category],
                format: 'pptx',
                category: config.category,
                isDefault: false,
                isActive: false,
                styles,
                customProperties: {
                    slideSize: {
                        width: 10,
                        height: 7.5,
                    },
                    orientation: 'landscape',
                    aspectRatio: '16:9',
                }
            };

            return templateManager.createTemplate(template);
        }, [templateManager, config.category]);

        // تحديث قالب PPTX
        const updatePptxTemplate = useCallback(async (
            templateId: string,
            updates: Partial<Template>
        ) => {
            await templateManager.updateTemplate(templateId, updates);
        }, [templateManager]);

        // حذف قالب PPTX
        const deletePptxTemplate = useCallback(async (templateId: string) => {
            await templateManager.deleteTemplate(templateId);
        }, [templateManager]);

        // تحديث نمط PPTX
        const updatePptxStyle = useCallback((
            templateId: string,
            styleId: string,
            properties: Record<string, any>
        ) => {
            templateManager.updateStyle(templateId, styleId, properties);
        }, [templateManager]);

        // إضافة نمط PPTX جديد
        const addPptxStyle = useCallback((
            templateId: string,
            style: TemplateStyle
        ) => {
            templateManager.addStyle(templateId, style);
        }, [templateManager]);

        // إزالة نمط PPTX
        const removePptxStyle = useCallback((
            templateId: string,
            styleId: string
        ) => {
            templateManager.removeStyle(templateId, styleId);
        }, [templateManager]);

        // الحصول على الأنماط الافتراضية لـ PPTX
        const getDefaultPptxStyles = useCallback((): Record<string, TemplateStyle> => {
            return {
                'title-slide': {
                    id: 'title-slide',
                    name: 'Title Slide',
                    category: 'layout',
                    properties: {
                        backgroundColor: '#ffffff',
                        titleStyle: {
                            fontSize: 44,
                            fontWeight: 'bold',
                            color: '#000000',
                            alignment: 'center',
                        },
                        subtitleStyle: {
                            fontSize: 24,
                            fontWeight: 'normal',
                            color: '#666666',
                            alignment: 'center',
                        }
                    }
                },
                'content-slide': {
                    id: 'content-slide',
                    name: 'Content Slide',
                    category: 'layout',
                    properties: {
                        backgroundColor: '#ffffff',
                        titleStyle: {
                            fontSize: 36,
                            fontWeight: 'bold',
                            color: '#000000',
                            alignment: 'left',
                        },
                        contentStyle: {
                            fontSize: 18,
                            fontWeight: 'normal',
                            color: '#000000',
                            lineHeight: 1.4,
                        }
                    }
                },
                'bullet-slide': {
                    id: 'bullet-slide',
                    name: 'Bullet Slide',
                    category: 'layout',
                    properties: {
                        backgroundColor: '#ffffff',
                        titleStyle: {
                            fontSize: 36,
                            fontWeight: 'bold',
                            color: '#000000',
                            alignment: 'left',
                        },
                        bulletStyle: {
                            fontSize: 18,
                            fontWeight: 'normal',
                            color: '#000000',
                            lineHeight: 1.4,
                            bulletColor: '#007acc',
                        }
                    }
                },
                'image-slide': {
                    id: 'image-slide',
                    name: 'Image Slide',
                    category: 'layout',
                    properties: {
                        backgroundColor: '#ffffff',
                        titleStyle: {
                            fontSize: 36,
                            fontWeight: 'bold',
                            color: '#000000',
                            alignment: 'center',
                        },
                        imageStyle: {
                            maxWidth: '80%',
                            maxHeight: '60%',
                            alignment: 'center',
                        }
                    }
                },
                'chart-slide': {
                    id: 'chart-slide',
                    name: 'Chart Slide',
                    category: 'layout',
                    properties: {
                        backgroundColor: '#ffffff',
                        titleStyle: {
                            fontSize: 36,
                            fontWeight: 'bold',
                            color: '#000000',
                            alignment: 'center',
                        },
                        chartStyle: {
                            backgroundColor: '#f8f9fa',
                            borderColor: '#dee2e6',
                            borderWidth: 1,
                        }
                    }
                },
                'conclusion-slide': {
                    id: 'conclusion-slide',
                    name: 'Conclusion Slide',
                    category: 'layout',
                    properties: {
                        backgroundColor: '#f8f9fa',
                        titleStyle: {
                            fontSize: 36,
                            fontWeight: 'bold',
                            color: '#000000',
                            alignment: 'center',
                        },
                        contentStyle: {
                            fontSize: 20,
                            fontWeight: 'normal',
                            color: '#000000',
                            alignment: 'center',
                            lineHeight: 1.5,
                        }
                    }
                }
            };
        }, []);

        // تطبيق نمط PPTX
        const applyPptxStyle = useCallback((
            templateId: string,
            slideType: string,
            styleId: string
        ) => {
            const template = templateManager.templates[templateId];
            if (!template) return;

            const style = template.styles[styleId];
            if (!style) return;

            console.log(`Applying PPTX style ${styleId} to ${slideType}`, style.properties);
        }, [templateManager.templates]);

        // الحصول على قوالب PPTX حسب الفئة
        const getPptxTemplatesByCategory = useCallback((category: TemplateCategory): Template[] => {
            return templateManager.getTemplatesByCategory(category).filter(template => template.format === 'pptx');
        }, [templateManager]);

        // التحقق من صحة قالب PPTX
        const validatePptxTemplate = useCallback((template: Template): boolean => {
            if (template.format !== 'pptx') return false;

            const requiredStyles = ['title-slide', 'content-slide'];
            const hasRequiredStyles = requiredStyles.every(styleId =>
                template.styles[styleId] && template.styles[styleId].properties
            );

            return hasRequiredStyles && templateManager.validateTemplate(template);
        }, [templateManager]);

        return {
            templates: templateManager.templates,
            activeTemplate: templateManager.activeTemplate,
            isLoading: templateManager.isLoading,
            isSaving: templateManager.isSaving,
            setActiveTemplate: templateManager.setActiveTemplate,
            createPptxTemplate,
            updatePptxTemplate,
            deletePptxTemplate,
            updatePptxStyle,
            addPptxStyle,
            removePptxStyle,
            getDefaultPptxStyles,
            applyPptxStyle,
            getPptxTemplatesByCategory,
            validatePptxTemplate,
        };
    };
}

// Hook افتراضي لـ PPTX
export const usePptxTemplate = createPptxTemplateHook({ category: 'presentation' });
