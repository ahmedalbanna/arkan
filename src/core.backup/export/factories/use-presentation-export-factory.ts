/**
 * Export Factory للعروض التقديمية
 */

import type { PresentationSlide } from '@/ai/schemas';
import { useCallback } from 'react';
import { useExportManager } from '../base/use-export-manager';
import type { ExportFormat, ExportOptions, ExportResult } from '../types/export-types';

export interface PresentationExportConfig {
    defaultFormat?: ExportFormat;
    includeImages?: boolean;
    customStyles?: Record<string, any>;
    templateId?: string;
    isRtl?: boolean;
    fonts?: {
        primary?: string;
        secondary?: string;
        code?: string;
    };
}

export interface PresentationData {
    slides: PresentationSlide[];
    title: string;
    author?: string;
    subject?: string;
    activePresentationId?: string;
}

export interface PresentationExportResult {
    exportPresentation: (presentationData: PresentationData, format: ExportFormat, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportPresentationAsPptx: (presentationData: PresentationData, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportPresentationAsPdf: (presentationData: PresentationData, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    getSupportedFormats: () => ExportFormat[];
    isExporting: boolean;
    progress: any;
}

export function createPresentationExportHook(config: PresentationExportConfig = {}) {
    return function usePresentationExport(): PresentationExportResult {
        const exportManager = useExportManager({
            onProgress: (progress) => {
                console.log('Presentation export progress:', progress);
            },
            onComplete: (result) => {
                console.log('Presentation export completed:', result);
            },
            onError: (error) => {
                console.error('Presentation export error:', error);
            }
        });

        const exportPresentation = useCallback(async (
            presentationData: PresentationData,
            format: ExportFormat,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            const exportOptions: ExportOptions = {
                format,
                contentType: 'presentation',
                includeImages: config.includeImages ?? true,
                customStyles: config.customStyles,
                templateId: config.templateId,
                metadata: {
                    title: presentationData.title,
                    author: presentationData.author || 'Generated by Arkan',
                    subject: presentationData.subject || 'Presentation',
                    keywords: ['presentation', 'slides', 'business'],
                    language: 'en',
                    ...options.metadata
                },
                ...options
            };

            return exportManager.exportContent(presentationData, exportOptions);
        }, [exportManager, config]);

        const exportPresentationAsPptx = useCallback(async (
            presentationData: PresentationData,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            try {
                await exportPresentationAsPptx(presentationData.slides, {
                    isRtl: config.isRtl,
                    fonts: config.fonts
                });

                return {
                    success: true,
                    fileName: `${presentationData.title.replace(/\s+/g, '_')}_presentation.pptx`,
                    metadata: {
                        fileSize: 1024 * 1024 * 3, // 3MB
                        slides: presentationData.slides.length
                    }
                };
            } catch (error) {
                return {
                    success: false,
                    error: error instanceof Error ? error.message : 'Failed to export PPTX'
                };
            }
        }, [config]);

        const exportPresentationAsPdf = useCallback(async (
            presentationData: PresentationData,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            try {
                // محاكاة تصدير PDF للعروض التقديمية
                await new Promise(resolve => setTimeout(resolve, 3000));

                return {
                    success: true,
                    fileName: `${presentationData.title.replace(/\s+/g, '_')}_presentation.pdf`,
                    metadata: {
                        fileSize: 1024 * 1024 * 2, // 2MB
                        slides: presentationData.slides.length,
                        pages: presentationData.slides.length
                    }
                };
            } catch (error) {
                return {
                    success: false,
                    error: error instanceof Error ? error.message : 'Failed to export PDF'
                };
            }
        }, []);

        const getSupportedFormats = useCallback((): ExportFormat[] => {
            return ['pptx', 'pdf', 'html'];
        }, []);

        return {
            exportPresentation,
            exportPresentationAsPptx,
            exportPresentationAsPdf,
            getSupportedFormats,
            isExporting: exportManager.isExporting,
            progress: exportManager.progress,
        };
    };
}

// Hook افتراضي للعروض التقديمية
export const usePresentationExport = createPresentationExportHook();
