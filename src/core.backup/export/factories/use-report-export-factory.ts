/**
 * Export Factory للتقارير
 */

import { useCallback } from 'react';
import { useExportManager } from '../base/use-export-manager';
import type { ExportFormat, ExportOptions, ExportResult } from '../types/export-types';

export interface ReportExportConfig {
    defaultFormat?: ExportFormat;
    includeDiagrams?: boolean;
    includeImages?: boolean;
    customStyles?: Record<string, any>;
    templateId?: string;
}

export interface ReportData {
    sections: { [key: string]: string };
    diagrams?: { [key: string]: { plantUmlCode: string; imageUrl: string } };
    title: string;
    translatedTitles?: { [key: string]: string };
    sectionsToInclude?: string[];
}

export interface ReportExportResult {
    exportReport: (reportData: ReportData, format: ExportFormat, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportReportAsPdf: (reportData: ReportData, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportReportAsDocx: (reportData: ReportData, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    getSupportedFormats: () => ExportFormat[];
    isExporting: boolean;
    progress: any;
}

export function createReportExportHook(config: ReportExportConfig = {}) {
    return function useReportExport(): ReportExportResult {
        const exportManager = useExportManager({
            onProgress: (progress) => {
                console.log('Report export progress:', progress);
            },
            onComplete: (result) => {
                console.log('Report export completed:', result);
            },
            onError: (error) => {
                console.error('Report export error:', error);
            }
        });

        const exportReport = useCallback(async (
            reportData: ReportData,
            format: ExportFormat,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            const exportOptions: ExportOptions = {
                format,
                contentType: 'report',
                includeImages: config.includeImages ?? true,
                includeDiagrams: config.includeDiagrams ?? true,
                customStyles: config.customStyles,
                templateId: config.templateId,
                metadata: {
                    title: reportData.title,
                    author: 'Generated by Arkan',
                    subject: 'Project Report',
                    keywords: ['report', 'analysis', 'project'],
                    language: 'en',
                    ...options.metadata
                },
                ...options
            };

            return exportManager.exportContent(reportData, exportOptions);
        }, [exportManager, config]);

        const exportReportAsPdf = useCallback(async (
            reportData: ReportData,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            try {
                // محاكاة تصدير PDF للتقارير
                await new Promise(resolve => setTimeout(resolve, 2000));

                return {
                    success: true,
                    fileName: `${reportData.title.replace(/\s+/g, '_')}_report.pdf`,
                    metadata: {
                        fileSize: 1024 * 1024 * 2, // 2MB
                        pages: 15,
                        sections: Object.keys(reportData.sections).length
                    }
                };
            } catch (error) {
                return {
                    success: false,
                    error: error instanceof Error ? error.message : 'Failed to export PDF'
                };
            }
        }, []);

        const exportReportAsDocx = useCallback(async (
            reportData: ReportData,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            try {
                await exportReportAsDocx(
                    reportData.sections,
                    reportData.diagrams || {},
                    reportData.title,
                    reportData.translatedTitles || {},
                    reportData.sectionsToInclude
                );

                return {
                    success: true,
                    fileName: `${reportData.title.replace(/\s+/g, '_')}_report.docx`,
                    metadata: {
                        fileSize: 1024 * 1024 * 2, // 2MB
                        pages: 15,
                        sections: Object.keys(reportData.sections).length
                    }
                };
            } catch (error) {
                return {
                    success: false,
                    error: error instanceof Error ? error.message : 'Failed to export DOCX'
                };
            }
        }, []);

        const getSupportedFormats = useCallback((): ExportFormat[] => {
            return ['pdf', 'docx', 'html'];
        }, []);

        return {
            exportReport,
            exportReportAsPdf,
            exportReportAsDocx,
            getSupportedFormats,
            isExporting: exportManager.isExporting,
            progress: exportManager.progress,
        };
    };
}

// Hook افتراضي للتقارير
export const useReportExport = createReportExportHook();
