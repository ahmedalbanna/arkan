/**
 * Export Factory للمقترحات
 */

import type { ProjectProposal } from '@/lib/models/project-proposal';
import { useCallback } from 'react';
import { useExportManager } from '../base/use-export-manager';
import type { ExportFormat, ExportOptions, ExportResult } from '../types/export-types';

export interface ProposalExportConfig {
    defaultFormat?: ExportFormat;
    includeImages?: boolean;
    customStyles?: Record<string, any>;
    templateId?: string;
}

export interface ProposalExportResult {
    exportProposal: (proposal: ProjectProposal, format: ExportFormat, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportProposalAsPdf: (proposal: ProjectProposal, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportProposalAsDocx: (proposal: ProjectProposal, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    getSupportedFormats: () => ExportFormat[];
    isExporting: boolean;
    progress: any;
}

export function createProposalExportHook(config: ProposalExportConfig = {}) {
    return function useProposalExport(): ProposalExportResult {
        const exportManager = useExportManager({
            onProgress: (progress) => {
                console.log('Export progress:', progress);
            },
            onComplete: (result) => {
                console.log('Export completed:', result);
            },
            onError: (error) => {
                console.error('Export error:', error);
            }
        });

        const exportProposal = useCallback(async (
            proposal: ProjectProposal,
            format: ExportFormat,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            const exportOptions: ExportOptions = {
                format,
                contentType: 'proposal',
                includeImages: config.includeImages ?? true,
                customStyles: config.customStyles,
                templateId: config.templateId,
                metadata: {
                    title: proposal.title,
                    author: 'Generated by Arkan',
                    subject: proposal.category,
                    keywords: ['proposal', 'business', 'project'],
                    language: 'en',
                    ...options.metadata
                },
                ...options
            };

            return exportManager.exportContent(proposal, exportOptions);
        }, [exportManager, config]);

        const exportProposalAsPdf = useCallback(async (
            proposal: ProjectProposal,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            return exportProposal(proposal, 'pdf', options);
        }, [exportProposal]);

        const exportProposalAsDocx = useCallback(async (
            proposal: ProjectProposal,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            return exportProposal(proposal, 'docx', options);
        }, [exportProposal]);

        const getSupportedFormats = useCallback((): ExportFormat[] => {
            return ['pdf', 'docx', 'html'];
        }, []);

        return {
            exportProposal,
            exportProposalAsPdf,
            exportProposalAsDocx,
            getSupportedFormats,
            isExporting: exportManager.isExporting,
            progress: exportManager.progress,
        };
    };
}

// Hook افتراضي للمقترحات
export const useProposalExport = createProposalExportHook();
