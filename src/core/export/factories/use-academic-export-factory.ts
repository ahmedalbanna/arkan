/**
 * Export Factory للحلول الأكاديمية
 */

import type { AnalyzedDocument, SolvedDocument } from '@/ai/schemas';
import { exportDocumentAsDocx } from '@/lib/academic-exporter';
import { useCallback } from 'react';
import { useExportManager } from '../base/use-export-manager';
import type { ExportFormat, ExportOptions, ExportResult } from '../types/export-types';

export interface AcademicExportConfig {
    defaultFormat?: ExportFormat;
    includeSteps?: boolean;
    includeExplanation?: boolean;
    customStyles?: Record<string, any>;
    templateId?: string;
}

export interface AcademicData {
    analyzedDocument: AnalyzedDocument;
    solvedDocument: SolvedDocument;
    title: string;
    subject: string;
}

export interface AcademicExportResult {
    exportAcademicSolution: (academicData: AcademicData, format: ExportFormat, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportAcademicAsPdf: (academicData: AcademicData, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    exportAcademicAsDocx: (academicData: AcademicData, options?: Partial<ExportOptions>) => Promise<ExportResult>;
    getSupportedFormats: () => ExportFormat[];
    isExporting: boolean;
    progress: any;
}

export function createAcademicExportHook(config: AcademicExportConfig = {}) {
    return function useAcademicExport(): AcademicExportResult {
        const exportManager = useExportManager({
            onProgress: (progress) => {
                console.log('Academic export progress:', progress);
            },
            onComplete: (result) => {
                console.log('Academic export completed:', result);
            },
            onError: (error) => {
                console.error('Academic export error:', error);
            }
        });

        const exportAcademicSolution = useCallback(async (
            academicData: AcademicData,
            format: ExportFormat,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            const exportOptions: ExportOptions = {
                format,
                contentType: 'academic-solution',
                includeImages: true,
                customStyles: config.customStyles,
                templateId: config.templateId,
                metadata: {
                    title: academicData.title,
                    author: 'Generated by Arkan',
                    subject: academicData.subject,
                    keywords: ['academic', 'solution', 'education', academicData.subject],
                    language: 'en',
                    ...options.metadata
                },
                ...options
            };

            return exportManager.exportContent(academicData, exportOptions);
        }, [exportManager, config]);

        const exportAcademicAsPdf = useCallback(async (
            academicData: AcademicData,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            try {
                // محاكاة تصدير PDF للحلول الأكاديمية
                await new Promise(resolve => setTimeout(resolve, 2500));

                return {
                    success: true,
                    fileName: `${academicData.title.replace(/\s+/g, '_')}_solution.pdf`,
                    metadata: {
                        fileSize: 1024 * 1024 * 1.5, // 1.5MB
                        pages: 8,
                        sections: academicData.solvedDocument.solutions.length
                    }
                };
            } catch (error) {
                return {
                    success: false,
                    error: error instanceof Error ? error.message : 'Failed to export PDF'
                };
            }
        }, []);

        const exportAcademicAsDocx = useCallback(async (
            academicData: AcademicData,
            options: Partial<ExportOptions> = {}
        ): Promise<ExportResult> => {
            try {
                await exportDocumentAsDocx(
                    academicData.analyzedDocument,
                    academicData.solvedDocument,
                    'modern' // يمكن تمرير templateId من الخيارات
                );

                return {
                    success: true,
                    fileName: `${academicData.title.replace(/\s+/g, '_')}_solution.docx`,
                    metadata: {
                        fileSize: 1024 * 1024 * 1.5, // 1.5MB
                        pages: 8,
                        sections: academicData.solvedDocument.solutions.length
                    }
                };
            } catch (error) {
                return {
                    success: false,
                    error: error instanceof Error ? error.message : 'Failed to export DOCX'
                };
            }
        }, []);

        const getSupportedFormats = useCallback((): ExportFormat[] => {
            return ['pdf', 'docx', 'html'];
        }, []);

        return {
            exportAcademicSolution,
            exportAcademicAsPdf,
            exportAcademicAsDocx,
            getSupportedFormats,
            isExporting: exportManager.isExporting,
            progress: exportManager.progress,
        };
    };
}

// Hook افتراضي للحلول الأكاديمية
export const useAcademicExport = createAcademicExportHook();
