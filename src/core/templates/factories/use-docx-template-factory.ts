/**
 * Template Factory لملفات DOCX
 */

import { useCallback } from 'react';
import { useTemplateManager } from '../managers/use-template-manager';
import type { Template, TemplateCategory, TemplateStyle } from '../types/template-types';

export interface DocxTemplateConfig {
    category: TemplateCategory;
    autoSave?: boolean;
    validateStyles?: boolean;
}

export interface DocxTemplateResult {
    templates: Record<string, Template>;
    activeTemplate: Template | null;
    isLoading: boolean;
    isSaving: boolean;

    // إدارة القوالب
    setActiveTemplate: (templateId: string) => void;
    createDocxTemplate: (name: string, description: string, styles: Record<string, TemplateStyle>) => Promise<string>;
    updateDocxTemplate: (templateId: string, updates: Partial<Template>) => Promise<void>;
    deleteDocxTemplate: (templateId: string) => Promise<void>;

    // إدارة الأنماط
    updateDocxStyle: (templateId: string, styleId: string, properties: Record<string, any>) => void;
    addDocxStyle: (templateId: string, style: TemplateStyle) => void;
    removeDocxStyle: (templateId: string, styleId: string) => void;

    // الأنماط الافتراضية
    getDefaultDocxStyles: () => Record<string, TemplateStyle>;
    applyDocxStyle: (templateId: string, elementType: string, styleId: string) => void;

    // الوظائف المساعدة
    getDocxTemplatesByCategory: (category: TemplateCategory) => Template[];
    validateDocxTemplate: (template: Template) => boolean;
}

export function createDocxTemplateHook(config: DocxTemplateConfig) {
    return function useDocxTemplate(): DocxTemplateResult {
        const templateManager = useTemplateManager({
            autoSave: config.autoSave ?? true,
            validateStyles: config.validateStyles ?? true,
            onStyleChange: (templateId, styleId, changes) => {
                console.log(`DOCX style changed: ${templateId}.${styleId}`, changes);
            },
            onTemplateChange: (templateId, changes) => {
                console.log(`DOCX template changed: ${templateId}`, changes);
            }
        });

        // إنشاء قالب DOCX جديد
        const createDocxTemplate = useCallback(async (
            name: string,
            description: string,
            styles: Record<string, TemplateStyle>
        ): Promise<string> => {
            const template: Omit<Template, 'id' | 'createdAt' | 'updatedAt'> = {
                name,
                description,
                version: '1.0.0',
                author: 'Generated by Arkan',
                tags: ['docx', config.category],
                format: 'docx',
                category: config.category,
                isDefault: false,
                isActive: false,
                styles,
                customProperties: {
                    pageSize: 'A4',
                    margins: {
                        top: 1,
                        bottom: 1,
                        left: 1,
                        right: 1,
                    },
                    orientation: 'portrait',
                }
            };

            return templateManager.createTemplate(template);
        }, [templateManager, config.category]);

        // تحديث قالب DOCX
        const updateDocxTemplate = useCallback(async (
            templateId: string,
            updates: Partial<Template>
        ) => {
            await templateManager.updateTemplate(templateId, updates);
        }, [templateManager]);

        // حذف قالب DOCX
        const deleteDocxTemplate = useCallback(async (templateId: string) => {
            await templateManager.deleteTemplate(templateId);
        }, [templateManager]);

        // تحديث نمط DOCX
        const updateDocxStyle = useCallback((
            templateId: string,
            styleId: string,
            properties: Record<string, any>
        ) => {
            templateManager.updateStyle(templateId, styleId, properties);
        }, [templateManager]);

        // إضافة نمط DOCX جديد
        const addDocxStyle = useCallback((
            templateId: string,
            style: TemplateStyle
        ) => {
            templateManager.addStyle(templateId, style);
        }, [templateManager]);

        // إزالة نمط DOCX
        const removeDocxStyle = useCallback((
            templateId: string,
            styleId: string
        ) => {
            templateManager.removeStyle(templateId, styleId);
        }, [templateManager]);

        // الحصول على الأنماط الافتراضية لـ DOCX
        const getDefaultDocxStyles = useCallback((): Record<string, TemplateStyle> => {
            return {
                'title': {
                    id: 'title',
                    name: 'Title',
                    category: 'typography',
                    properties: {
                        fontSize: 24,
                        fontWeight: 'bold',
                        color: '#000000',
                        alignment: 'center',
                        spacing: { before: 240, after: 120 }
                    }
                },
                'heading1': {
                    id: 'heading1',
                    name: 'Heading 1',
                    category: 'typography',
                    properties: {
                        fontSize: 18,
                        fontWeight: 'bold',
                        color: '#000000',
                        spacing: { before: 240, after: 120 }
                    }
                },
                'heading2': {
                    id: 'heading2',
                    name: 'Heading 2',
                    category: 'typography',
                    properties: {
                        fontSize: 16,
                        fontWeight: 'bold',
                        color: '#000000',
                        spacing: { before: 180, after: 90 }
                    }
                },
                'body': {
                    id: 'body',
                    name: 'Body Text',
                    category: 'typography',
                    properties: {
                        fontSize: 12,
                        fontWeight: 'normal',
                        color: '#000000',
                        lineHeight: 1.5,
                        spacing: { after: 120 }
                    }
                },
                'paragraph': {
                    id: 'paragraph',
                    name: 'Paragraph',
                    category: 'typography',
                    properties: {
                        fontSize: 12,
                        fontWeight: 'normal',
                        color: '#000000',
                        lineHeight: 1.5,
                        spacing: { after: 120 }
                    }
                },
                'list': {
                    id: 'list',
                    name: 'List',
                    category: 'typography',
                    properties: {
                        fontSize: 12,
                        fontWeight: 'normal',
                        color: '#000000',
                        lineHeight: 1.5,
                        spacing: { after: 60 }
                    }
                },
                'quote': {
                    id: 'quote',
                    name: 'Quote',
                    category: 'typography',
                    properties: {
                        fontSize: 12,
                        fontWeight: 'italic',
                        color: '#666666',
                        alignment: 'center',
                        spacing: { before: 120, after: 120 }
                    }
                }
            };
        }, []);

        // تطبيق نمط DOCX
        const applyDocxStyle = useCallback((
            templateId: string,
            elementType: string,
            styleId: string
        ) => {
            const template = templateManager.templates[templateId];
            if (!template) return;

            const style = template.styles[styleId];
            if (!style) return;

            console.log(`Applying DOCX style ${styleId} to ${elementType}`, style.properties);
        }, [templateManager.templates]);

        // الحصول على قوالب DOCX حسب الفئة
        const getDocxTemplatesByCategory = useCallback((category: TemplateCategory): Template[] => {
            return templateManager.getTemplatesByCategory(category).filter(template => template.format === 'docx');
        }, [templateManager]);

        // التحقق من صحة قالب DOCX
        const validateDocxTemplate = useCallback((template: Template): boolean => {
            if (template.format !== 'docx') return false;

            const requiredStyles = ['title', 'body', 'paragraph'];
            const hasRequiredStyles = requiredStyles.every(styleId =>
                template.styles[styleId] && template.styles[styleId].properties
            );

            return hasRequiredStyles && templateManager.validateTemplate(template);
        }, [templateManager]);

        return {
            templates: templateManager.templates,
            activeTemplate: templateManager.activeTemplate,
            isLoading: templateManager.isLoading,
            isSaving: templateManager.isSaving,
            setActiveTemplate: templateManager.setActiveTemplate,
            createDocxTemplate,
            updateDocxTemplate,
            deleteDocxTemplate,
            updateDocxStyle,
            addDocxStyle,
            removeDocxStyle,
            getDefaultDocxStyles,
            applyDocxStyle,
            getDocxTemplatesByCategory,
            validateDocxTemplate,
        };
    };
}

// Hook افتراضي لـ DOCX
export const useDocxTemplate = createDocxTemplateHook({ category: 'document' });
