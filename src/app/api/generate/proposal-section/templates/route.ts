export async function GET(request: NextRequest) {
    try {
        console.log('📋 طلب قوالب أقسام المقترح');

        const { searchParams } = new URL(request.url);
        const type = searchParams.get('type');

        let result;

        if (type && templates[type as keyof typeof templates]) {
            // إرجاع قوالب نوع محدد
            result = templates[type as keyof typeof templates];
            console.log(`✅ تم إرجاع ${result.length} قالب لنوع: ${type}`);
        } else {
            // إرجاع جميع القوالب
            result = Object.values(templates).flat();
            console.log(`✅ تم إرجاع ${result.length} قالب إجمالي`);
        }

        // التحقق من صحة البيانات
        const validatedResult = z.array(TemplateSchema).parse(result);

        return NextResponse.json(validatedResult, {
            status: 200,
            headers: {
                'Content-Type': 'application/json',
                'Cache-Control': 'public, max-age=3600' // cache for 1 hour
            }
        });

    } catch (error) {
        console.error('❌ خطأ في جلب قوالب أقسام المقترح:', error);

        return NextResponse.json(
            {
                error: 'فشل في جلب القوالب',
                message: error instanceof Error ? error.message : 'خطأ غير معروف'
            },
            { status: 500 }
        );
    }
}

// دعم CORS
export async function OPTIONS(request: NextRequest) {
    return new NextResponse(null, {
        status: 200,
        headers: {
            'Access-Control-Allow-Origin': '*',
            'Access-Control-Allow-Methods': 'GET, OPTIONS',
            'Access-Control-Allow-Headers': 'Content-Type, Authorization',
        },
    });
}
