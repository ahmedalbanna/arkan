/**
 * Hook محسن للتصدير يستخدم النظام الجديد من src/core
 */

'use client';

import type { AnalyzedDocument, PresentationSlide, SolvedDocument } from '@/ai/schemas';
import { useAcademicExport, usePresentationExport, useProposalExport, useReportExport } from '@/core/export';

import type { ProjectProposal } from '@/lib/models/proposal';

export interface ExportEnhancedOptions {
    includeImages?: boolean;
    includeDiagrams?: boolean;
    templateId?: string;
    customStyles?: Record<string, any>;
}

export function useExportEnhanced() {
    // Export Hooks من النظام الجديد
    const proposalExport = useProposalExport();
    const reportExport = useReportExport();
    const presentationExport = usePresentationExport();
    const academicExport = useAcademicExport();

    // تصدير المقترحات
    const exportProposal = async (
        proposal: ProjectProposal,
        format: 'pdf' | 'docx' | 'html',
        options: ExportEnhancedOptions = {}
    ) => {
        const result = await proposalExport.exportProposal(proposal, format, {
            includeImages: options.includeImages ?? true,
            templateId: options.templateId,
            customStyles: options.customStyles,
            metadata: {
                title: proposal.title,
                author: 'Generated by Arkan',
                subject: proposal.category,
            }
        });

        return result;
    };

    // تصدير التقارير
    const exportReport = async (
        reportData: {
            sections: { [key: string]: string };
            diagrams?: { [key: string]: { plantUmlCode: string; imageUrl: string } };
            title: string;
            translatedTitles?: { [key: string]: string };
            sectionsToInclude?: string[];
        },
        format: 'pdf' | 'docx' | 'html',
        options: ExportEnhancedOptions = {}
    ) => {
        const result = await reportExport.exportReport(reportData, format, {
            includeImages: options.includeImages ?? true,
            includeDiagrams: options.includeDiagrams ?? true,
            templateId: options.templateId,
            customStyles: options.customStyles,
            metadata: {
                title: reportData.title,
                author: 'Generated by Arkan',
                subject: 'Project Report',
            }
        });

        return result;
    };

    // تصدير العروض التقديمية
    const exportPresentation = async (
        slides: PresentationSlide[],
        title: string,
        format: 'pptx' | 'pdf' | 'html',
        options: ExportEnhancedOptions = {}
    ) => {
        const result = await presentationExport.exportPresentation({
            slides,
            title,
            author: 'Generated by Arkan',
            subject: 'Presentation',
        }, format, {
            includeImages: options.includeImages ?? true,
            templateId: options.templateId,
            customStyles: options.customStyles,
            metadata: {
                title,
                author: 'Generated by Arkan',
                subject: 'Presentation',
            }
        });

        return result;
    };

    // تصدير الحلول الأكاديمية
    const exportAcademicSolution = async (
        analyzedDoc: AnalyzedDocument,
        solvedDoc: SolvedDocument,
        format: 'pdf' | 'docx' | 'html',
        options: ExportEnhancedOptions = {}
    ) => {
        const result = await academicExport.exportAcademicSolution({
            analyzedDocument: analyzedDoc,
            solvedDocument: solvedDoc,
            title: analyzedDoc.title,
            subject: analyzedDoc.subject,
        }, format, {
            includeImages: options.includeImages ?? true,
            templateId: options.templateId,
            customStyles: options.customStyles,
            metadata: {
                title: analyzedDoc.title,
                author: 'Generated by Arkan',
                subject: analyzedDoc.subject,
            }
        });

        return result;
    };

    // الحصول على التنسيقات المدعومة
    const getSupportedFormats = (contentType: 'proposal' | 'report' | 'presentation' | 'academic') => {
        switch (contentType) {
            case 'proposal':
                return proposalExport.getSupportedFormats();
            case 'report':
                return reportExport.getSupportedFormats();
            case 'presentation':
                return presentationExport.getSupportedFormats();
            case 'academic':
                return academicExport.getSupportedFormats();
            default:
                return ['pdf'];
        }
    };

    // حالة التصدير العامة
    const isExporting =
        proposalExport.isExporting ||
        reportExport.isExporting ||
        presentationExport.isExporting ||
        academicExport.isExporting;

    return {
        // وظائف التصدير
        exportProposal,
        exportReport,
        exportPresentation,
        exportAcademicSolution,

        // وظائف مساعدة
        getSupportedFormats,

        // الحالة
        isExporting,

        // الحالة التفصيلية لكل نوع
        isProposalExporting: proposalExport.isExporting,
        isReportExporting: reportExport.isExporting,
        isPresentationExporting: presentationExport.isExporting,
        isAcademicExporting: academicExport.isExporting,

        // التقدم
        proposalProgress: proposalExport.progress,
        reportProgress: reportExport.progress,
        presentationProgress: presentationExport.progress,
        academicProgress: academicExport.progress,
    };
}
