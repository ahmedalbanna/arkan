
'use client';

import { useState } from 'react';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { ArrowLeft, Loader2, Sparkles, CheckCircle } from 'lucide-react';
import { GeneratePresentationOutlineOutput } from '@/ai/flows/generate-presentation-outline';
import Image from 'next/image';
import { usePresentationStore } from '@/hooks/usePresentationStore';
import { toast } from '@/hooks/use-toast';

const templates = [
  { name: 'Minimalist', imgSrc: 'https://placehold.co/300x200.png', dataAiHint: 'minimalist presentation', id: 'minimalist' },
  { name: 'Professional', imgSrc: 'https://placehold.co/300x200.png', dataAiHint: 'professional presentation', id: 'professional' },
  { name: 'Creative', imgSrc: 'https://placehold.co/300x200.png', dataAiHint: 'creative presentation', id: 'creative' },
  { name: 'Technology', imgSrc: 'https://placehold.co/300x200.png', dataAiHint: 'technology presentation', id: 'technology' },
];

export function CreateWithAiTemplates({
  outline,
  onBack,
}: {
  outline: GeneratePresentationOutlineOutput;
  onBack: () => void;
}) {
  const [selectedTemplate, setSelectedTemplate] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const addPresentationToHistory = usePresentationStore(state => state.addPresentationToHistory);

  const handleSelectTemplate = (templateId: string) => {
    setIsLoading(true);
    setSelectedTemplate(templateId);

    // Simulate presentation creation
    setTimeout(() => {
        const newPresentation = {
            id: new Date().toISOString(),
            name: outline.cover.title || 'Untitled Presentation',
            slides: outline.outline.map(item => ({
                title: item.title,
                content: item.content.split('\n').filter(s => s.trim()),
                speakerNotes: 'Generated by AI. Please review and edit speaker notes.',
                layout: 'title_and_content' as const,
            }))
        };
        addPresentationToHistory(newPresentation);
        setIsLoading(false);
        toast({
            title: "Presentation Created!",
            description: `Successfully generated "${newPresentation.name}".`,
            icon: <CheckCircle className="h-5 w-5 text-green-500" />
        });
        // Here you would typically close the panel, but for the demo we keep it open
        // to show the final state.
    }, 2000);
  };

  return (
    <Card className="absolute right-0 top-0 bottom-0 w-80 bg-white z-20 shadow-lg flex flex-col rounded-none border-l">
      <CardHeader className="flex-row items-center gap-2 p-2 border-b">
        <Button variant="ghost" size="icon" className="h-7 w-7" onClick={onBack}>
          <ArrowLeft className="w-4 h-4" />
        </Button>
        <div>
            <CardTitle className="text-base font-semibold">Choose a Template</CardTitle>
            <CardDescription className="text-sm">Select a visual style for your presentation.</CardDescription>
        </div>
      </CardHeader>
      <CardContent className="p-4 flex-grow overflow-y-auto">
        {isLoading ? (
            <div className="flex flex-col items-center justify-center h-full text-center text-muted-foreground">
                <Loader2 className="w-12 h-12 animate-spin text-primary mb-4" />
                <p className="font-semibold">Creating your presentation...</p>
                <p className="text-xs">Applying the "{selectedTemplate}" template.</p>
            </div>
        ) : (
            <div className="grid grid-cols-1 gap-4">
                {templates.map(template => (
                    <button key={template.id} onClick={() => handleSelectTemplate(template.id)} className="border-2 border-transparent hover:border-primary rounded-lg transition-all">
                        <Image 
                            src={template.imgSrc} 
                            alt={template.name} 
                            width={300} 
                            height={200}
                            data-ai-hint={template.dataAiHint}
                            className="rounded-md"
                        />
                        <p className="text-sm font-medium mt-1">{template.name}</p>
                    </button>
                ))}
            </div>
        )}
      </CardContent>
    </Card>
  );
}
